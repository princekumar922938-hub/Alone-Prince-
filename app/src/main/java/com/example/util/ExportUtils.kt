    /**
     * Converts expenses to CSV format with UTF-8 BOM so Excel opens it with proper Indian formatting and Rupee symbols.
     */
    fun generateTransactionsCsv(expenses: List<ExpenseEntity>): String {
        val sb = StringBuilder()
        // CSV Header
        sb.append("ID,Date (DD/MM/YYYY),Title,Category,Amount (INR),Amount (Paise),Payment Method,Time,Notes\n")
        for (e in expenses) {
            val formattedDate = DateUtils.formatDate(e.expenseDate)
            val rupees = CurrencyUtils.formatInr(e.amountPaise).replace("₹", "INR ")
            val safeTitle = escapeCsv(e.title)
            val safeCategory = escapeCsv(e.categoryName)
            val safePayment = escapeCsv(e.paymentMethod)
            val safeTime = escapeCsv(e.expenseTime)
            val safeNotes = escapeCsv(e.notes)
            sb.append("${e.id},\"$formattedDate\",\"$safeTitle\",\"$safeCategory\",\"$rupees\",${e.amountPaise},\"$safePayment\",\"$safeTime\",\"$safeNotes\"\n")
        }
        return sb.toString()
    }

    fun generateCategorySummaryCsv(summaries: List<CategorySummary>, totalPaise: Long): String {
        val sb = StringBuilder()
        sb.append("Category,Total Expenditure (INR),Transaction Count,Average (INR),Percentage (%)\n")
        for (c in summaries) {
            val amount = CurrencyUtils.formatInr(c.totalPaise).replace("₹", "INR ")
            val avg = CurrencyUtils.formatInr(c.averagePaise).replace("₹", "INR ")
            val pct = String.format("%.2f%%", c.percentage)
            sb.append("\"${escapeCsv(c.categoryName)}\",\"$amount\",${c.transactionCount},\"$avg\",\"$pct\"\n")
        }
        sb.append("\nTOTAL,\"${CurrencyUtils.formatInr(totalPaise).replace("₹", "INR ")}\",,\n")
        return sb.toString()
    }

    fun generateDetailedReportText(
        periodLabel: String,
        totalPaise: Long,
        transactionCount: Int,
        avgDailyPaise: Long,
        activeDayAvgPaise: Long,
        highestDay: String?,
        highestCategory: String?,
        categorySummaries: List<CategorySummary>
    ): String {
        val sb = StringBuilder()
        sb.append("=========================================\n")
        sb.append("         SMART KHARCHA REPORT           \n")
        sb.append("=========================================\n\n")
        sb.append("Reporting Period: $periodLabel\n")
        sb.append("Total Expenditure: ${CurrencyUtils.formatInr(totalPaise)}\n")
        sb.append("Total Transactions: $transactionCount\n")
        sb.append("Average Daily Expense: ${CurrencyUtils.formatInr(avgDailyPaise)}\n")
        sb.append("Active Day Average: ${CurrencyUtils.formatInr(activeDayAvgPaise)}\n")
        highestDay?.let { sb.append("Highest Spending Day: $it\n") }
        highestCategory?.let { sb.append("Highest Spending Category: $it\n") }
        sb.append("\n-----------------------------------------\n")
        sb.append("CATEGORY BREAKDOWN:\n")
        sb.append("-----------------------------------------\n")
        for (c in categorySummaries) {
            sb.append(
                String.format(
                    "%-26s %12s (%5.1f%%) [%d txns]\n",
                    c.categoryName.take(25),
                    CurrencyUtils.formatInr(c.totalPaise),
                    c.percentage,
                    c.transactionCount
                )
            )
        }
        sb.append("-----------------------------------------\n")
        sb.append("Generated by Smart Kharcha on ${DateUtils.formatDate(DateUtils.todayEpochDay())}\n")
        return sb.toString()
    }

    /**
     * Backs up expenses, categories, and budgets into structured JSON.
     */
    fun createJsonBackup(
        expenses: List<ExpenseEntity>,
        categories: List<CategoryEntity>,
        budgets: List<BudgetEntity>
    ): String {
        val root = JSONObject()
        root.put("app", "Smart Kharcha")
        root.put("version", 1)
        root.put("exported_at", System.currentTimeMillis())

        val expArr = JSONArray()
        for (e in expenses) {
            val obj = JSONObject()
            obj.put("id", e.id)
            obj.put("title", e.title)
            obj.put("amount_paise", e.amountPaise)
            obj.put("category_id", e.categoryId)
            obj.put("category_name", e.categoryName)
            obj.put("expense_date", e.expenseDate)
            obj.put("expense_time", e.expenseTime)
            obj.put("payment_method", e.paymentMethod)
            obj.put("notes", e.notes)
            obj.put("created_at", e.createdAt)
            obj.put("updated_at", e.updatedAt)
            expArr.put(obj)
        }
        root.put("expenses", expArr)

        val catArr = JSONArray()
        for (c in categories) {
            val obj = JSONObject()
            obj.put("id", c.id)
            obj.put("name", c.name)
            obj.put("icon_key", c.iconKey)
            obj.put("color_hex", c.colorHex)
            obj.put("is_default", c.isDefault)
            obj.put("is_active", c.isActive)
            catArr.put(obj)
        }
        root.put("categories", catArr)

        val bgtArr = JSONArray()
        for (b in budgets) {
            val obj = JSONObject()
            obj.put("month_key", b.monthKey)
            obj.put("overall_budget_paise", b.overallBudgetPaise)
            obj.put("category_budgets_json", b.categoryBudgetsJson)
            bgtArr.put(obj)
        }
        root.put("budgets", bgtArr)

        return root.toString(2)
    }

    /**
     * Validates and parses JSON backup.
     */
    fun parseJsonBackup(
        jsonString: String
    ): Triple<List<ExpenseEntity>, List<CategoryEntity>, List<BudgetEntity>>? {
        return try {
            val root = JSONObject(jsonString)
            if (!root.has("app") || root.getString("app") != "Smart Kharcha") {
                return null
            }

            val expList = mutableListOf<ExpenseEntity>()
            if (root.has("expenses")) {
                val arr = root.getJSONArray("expenses")
                for (i in 0 until arr.length()) {
                    val o = arr.getJSONObject(i)
                    expList.add(
                        ExpenseEntity(
                            id = o.optLong("id", 0L),
                            title = o.getString("title"),
                            amountPaise = o.getLong("amount_paise"),
                            categoryId = o.getLong("category_id"),
                            categoryName = o.getString("category_name"),
                            expenseDate = o.getLong("expense_date"),
                            expenseTime = o.optString("expense_time", ""),
                            paymentMethod = o.optString("payment_method", "Cash"),
                            notes = o.optString("notes", ""),
                            createdAt = o.optLong("created_at", System.currentTimeMillis()),
                            updatedAt = o.optLong("updated_at", System.currentTimeMillis())
                        )
                    )
                }
            }

            val catList = mutableListOf<CategoryEntity>()
            if (root.has("categories")) {
                val arr = root.getJSONArray("categories")
                for (i in 0 until arr.length()) {
                    val o = arr.getJSONObject(i)
                    catList.add(
                        CategoryEntity(
                            id = o.optLong("id", 0L),
                            name = o.getString("name"),
                            iconKey = o.optString("icon_key", "other"),
                            colorHex = o.optString("color_hex", "#3B82F6"),
                            isDefault = o.optBoolean("is_default", false),
                            isActive = o.optBoolean("is_active", true)
                        )
                    )
                }
            }

            val bgtList = mutableListOf<BudgetEntity>()
            if (root.has("budgets")) {
                val arr = root.getJSONArray("budgets")
                for (i in 0 until arr.length()) {
                    val o = arr.getJSONObject(i)
                    bgtList.add(
                        BudgetEntity(
                            monthKey = o.getString("month_key"),
                            overallBudgetPaise = o.optLong("overall_budget_paise", 0L),
                            categoryBudgetsJson = o.optString("category_budgets_json", "{}")
                        )
                    )
                }
            }

            Triple(expList, catList, bgtList)
        } catch (_: Exception) {
            null
        }
    }

    fun shareExportFile(context: Context, fileName: String, mimeType: String, content: String) {
        try {
            val cachePath = File(context.cacheDir, "exports")
            cachePath.mkdirs()
            val file = File(cachePath, fileName)
            FileOutputStream(file).use { out ->
                // Write UTF-8 BOM if CSV for MS Excel compatibility
                if (fileName.endsWith(".csv")) {
                    out.write(byteArrayOf(0xEF.toByte(), 0xBB.toByte(), 0xBF.toByte()))
                }
                out.write(content.toByteArray(Charsets.UTF_8))
            }

            val contentUri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = mimeType
                putExtra(Intent.EXTRA_STREAM, contentUri)
                putExtra(Intent.EXTRA_SUBJECT, fileName)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share or Export File"))
        } catch (e: Exception) {
            // Fallback plain text share if FileProvider is unavailable
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_SUBJECT, fileName)
                putExtra(Intent.EXTRA_TEXT, content)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share File"))
        }
    }

    fun shareAppApk(context: Context) {
        try {
            val srcApk = File(context.applicationInfo.sourceDir)
            val cachePath = File(context.cacheDir, "exports")
            cachePath.mkdirs()
            val destApk = File(cachePath, "SmartKharcha.apk")
            srcApk.inputStream().use { input ->
                destApk.outputStream().use { output ->
                    input.copyTo(output)
                }
            }
            val contentUri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                destApk
            )
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/vnd.android.package-archive"
                putExtra(Intent.EXTRA_STREAM, contentUri)
                putExtra(Intent.EXTRA_SUBJECT, "Smart Kharcha APK (Install File)")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share / Install Smart Kharcha APK"))
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    fun installCurrentApk(context: Context) {
        try {
            val srcApk = File(context.applicationInfo.sourceDir)
            val cachePath = File(context.cacheDir, "exports")
            cachePath.mkdirs()
            val destApk = File(cachePath, "SmartKharcha.apk")
            srcApk.inputStream().use { input ->
                destApk.outputStream().use { output ->
                    input.copyTo(output)
                }
            }
            val contentUri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                destApk
            )
            val installIntent = Intent(Intent.ACTION_VIEW).apply {
                setDataAndType(contentUri, "application/vnd.android.package-archive")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(installIntent)
        } catch (e: Exception) {
            // Fallback to sharing the APK file if direct package installer fails
            shareAppApk(context)
        }
    }

