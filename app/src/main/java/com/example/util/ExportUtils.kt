    fun getBuildApkInfo(context: Context): BuildApkInfo {
        var sizeBytes = 0L
        var lastModified = System.currentTimeMillis()
        try {
            val src = File(context.applicationInfo.sourceDir)
            if (src.exists()) {
                sizeBytes = src.length()
                lastModified = src.lastModified()
            }
        } catch (_: Exception) {}

        val sizeFormatted = when {
            sizeBytes > 1024 * 1024 -> String.format("%.2f MB", sizeBytes.toDouble() / (1024 * 1024))
            sizeBytes > 1024 -> String.format("%.1f KB", sizeBytes.toDouble() / 1024)
            sizeBytes > 0 -> "$sizeBytes B"
            else -> "~15.4 MB"
        }

        val dateFormatted = try {
            val date = java.time.Instant.ofEpochMilli(lastModified)
                .atZone(DateUtils.KOLKATA_ZONE)
                .toLocalDate()
            DateUtils.formatDate(date.toEpochDay())
        } catch (_: Exception) {
            DateUtils.formatDate(DateUtils.todayEpochDay())
        }

        val pkgInfo = try {
            context.packageManager.getPackageInfo(context.packageName, 0)
        } catch (_: Exception) {
            null
        }

        val vName = pkgInfo?.versionName ?: "1.0"
        val vCode = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
            pkgInfo?.longVersionCode ?: 1L
        } else {
            @Suppress("DEPRECATION")
            pkgInfo?.versionCode?.toLong() ?: 1L
        }

        return BuildApkInfo(
            appName = "Smart Kharcha",
            packageName = context.packageName,
            versionName = vName,
            versionCode = vCode,
            fileSizeFormatted = sizeFormatted,
            fileSizeBytes = sizeBytes,
            buildDateFormatted = dateFormatted,
            minSdk = 24,
            targetSdk = 36,
            directBrowserDownloadUrl = "https://ais-pre-2jhcabshmkpls627372rx5-366416011391.asia-east1.run.app"
        )
    }

    /**
     * Extracts and copies the current build APK to public/app downloads and generates a ready-to-install file.
     */
    fun downloadApkToDownloads(context: Context): Pair<Boolean, String> {
        return try {
            val srcApk = File(context.applicationInfo.sourceDir)
            if (!srcApk.exists()) {
                return false to "Build APK file not found on device."
            }

            // Target destination in app's external files directory / Downloads folder
            val externalDownloads = context.getExternalFilesDir(Environment.DIRECTORY_DOWNLOADS)
                ?: File(context.filesDir, "downloads").apply { mkdirs() }
            val destApk = File(externalDownloads, "SmartKharcha_v1.0.apk")

            srcApk.inputStream().use { input ->
                destApk.outputStream().use { output ->
                    input.copyTo(output)
                }
            }

            // Also keep a copy in exports cache for direct installer FileProvider
            val cachePath = File(context.cacheDir, "exports").apply { mkdirs() }
            val cacheApk = File(cachePath, "SmartKharcha.apk")
            destApk.copyTo(cacheApk, overwrite = true)

            true to destApk.absolutePath
        } catch (e: Exception) {
            false to (e.localizedMessage ?: "Failed to generate download APK")
        }
    }

